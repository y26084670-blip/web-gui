const loaded = await Promise.all(changes.map(async ([path, expected, addition]) => {
  const bytes = await readFile(resolve(root, path));
  const text = bytes.toString("utf8");
  return { path, expected, addition, bytes, text };
}));
if (loaded.every((item) => item.text.includes(marker))) process.exit(0);
const stamp = "Обновлено: " + new Date().toISOString().slice(0, 16).replace("T", " ") + " UTC.";
for (const item of loaded) {
  const actual = createHash("sha1").update(`blob ${item.bytes.length}\0`).update(item.bytes).digest("hex");
  if (actual !== item.expected) throw new Error(`Документ изменён вне инкремента: ${item.path}`);
  if (!/^Обновлено:.*$/m.test(item.text)) throw new Error(`Нет строки даты: ${item.path}`);
}
for (const item of loaded) {
  const updated = item.text.replace(/^Обновлено:.*$/m, stamp).trimEnd()
    + `\n\n${marker}\n\n${item.addition}`;
  await writeFile(resolve(root, item.path), updated);
  console.log(item.path);
}
